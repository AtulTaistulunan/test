E = html.escape
def card(title, fields):
    h = f'<div class="kc"><h4><span class="ktag">補充</span>{E(title)}</h4>'
    for lab, items in fields:
        h += f'<div class="kf"><span class="kl">{E(lab)}</span><span class="kv">' + ''.join(f'<div class="kline">{E(i)}</div>' for i in items) + '</span></div>'
    return h + '</div>'
