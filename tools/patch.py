    p = f"{D}/units/{u['id']}.json"; s = open(p, encoding='utf-8').read()
    for a, b in NAMES.items(): ren += s.count(a); s = s.replace(a, b)
    d = json.loads(s)
    add = ''.join(card(t, f) for t, f in CARDS.get(u['id'], [])); n += len(CARDS.get(u['id'], []))
    if add:
        assert d['notesHtml'].startswith('<div class="kgrid">') and d['notesHtml'].endswith('</div>'), u['id']
        d['notesHtml'] = d['notesHtml'][:-6] + add + '</div>'
    json.dump(d, open(p, 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
